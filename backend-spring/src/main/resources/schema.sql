CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(40) DEFAULT '', password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'user',
 points INT NOT NULL DEFAULT 0, recycled_kg DECIMAL(10,2) NOT NULL DEFAULT 0, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(180) NOT NULL, price INT NOT NULL, description TEXT,
 category VARCHAR(100) DEFAULT 'Eco Products', emoji VARCHAR(16) DEFAULT '♻️', image_url VARCHAR(500),
 stock_quantity INT NOT NULL DEFAULT 0, stock_status VARCHAR(30) NOT NULL DEFAULT 'IN_STOCK', is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pickups (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, plastic_type VARCHAR(100) NOT NULL, quantity DECIMAL(10,2) NOT NULL,
 description TEXT NOT NULL, house_landmark VARCHAR(255) DEFAULT '', street VARCHAR(255) NOT NULL, pincode VARCHAR(10) NOT NULL,
 city VARCHAR(120) NOT NULL, address VARCHAR(600) NOT NULL, image_url VARCHAR(500), status VARCHAR(30) NOT NULL DEFAULT 'pending',
 reward_points INT NOT NULL DEFAULT 0, available_dates JSON, slots JSON, scheduled_date VARCHAR(30), scheduled_slot VARCHAR(100),
 ai_classification VARCHAR(40), ai_confidence DECIMAL(6,5) DEFAULT 0, ai_labels JSON, ai_scanned_at VARCHAR(50),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_pickup_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS schedules (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pickup_id BIGINT NOT NULL UNIQUE, user_id BIGINT NOT NULL, scheduled_date VARCHAR(30) NOT NULL,
 time_slot VARCHAR(100) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'scheduled', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_schedule_pickup FOREIGN KEY(pickup_id) REFERENCES pickups(id) ON DELETE CASCADE,
 CONSTRAINT fk_schedule_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, title VARCHAR(180) NOT NULL, message TEXT NOT NULL, link VARCHAR(255) DEFAULT '/',
 is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notification_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, total_points INT NOT NULL, payment_method VARCHAR(80) DEFAULT 'Reward Points',
 payment_status VARCHAR(40) DEFAULT 'paid', status VARCHAR(40) DEFAULT 'confirmed', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_order_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL, product_name VARCHAR(180) NOT NULL,
 unit_price INT NOT NULL, quantity INT NOT NULL, CONSTRAINT fk_item_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS reward_transactions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, pickup_id BIGINT NULL, order_id BIGINT NULL, points_delta INT NOT NULL,
 reason VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_reward_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
